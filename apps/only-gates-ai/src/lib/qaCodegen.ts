import {
  buildQaModelInfo,
  contentTokens,
  createQuestionAnswerer,
  QA_ENGINE_VERSION,
  type QaDocument,
  type QaLexicon,
} from "./qaRuntime.ts";

export interface CompileQuestionAnswererInput {
  readonly documents: readonly QaDocument[];
  readonly suggestions?: readonly string[];
  readonly name: string;
  readonly lexicon: QaLexicon;
  /** Source text of `qaRuntime.ts`, inlined verbatim. */
  readonly runtimeSource: string;
  readonly createdAt?: string;
  readonly updatedAt?: string;
}

export interface CompiledQuestionAnswerer {
  readonly code: string;
  readonly filename: string;
  readonly engineVersion: number;
  readonly conceptCount: number;
  readonly variantCount: number;
  readonly questionWordCount: number;
  readonly uniqueTokenCount: number;
  readonly lexiconWordCount: number;
  readonly fingerprint: string;
  readonly lineCount: number;
  readonly byteLength: number;
}

function slugify(value: string): string {
  const slug = value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return slug.length > 0 ? slug : "qa-model";
}

function safeJson(value: unknown, space?: number): string {
  return (JSON.stringify(value, null, space) ?? "null")
    .replace(/</g, "\\u003c")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

function emitStringArray(
  name: string,
  values: readonly string[],
  perLine: number,
): string[] {
  if (values.length === 0) {
    return [`  ${name}: [],`];
  }

  const lines = [`  ${name}: [`];
  for (let index = 0; index < values.length; index += perLine) {
    lines.push(
      `    ${values
        .slice(index, index + perLine)
        .map((value) => safeJson(value))
        .join(", ")},`,
    );
  }
  lines.push("  ],");
  return lines;
}

/**
 * Emits a self-contained TypeScript module. The runtime source is inlined, so
 * the generated module has no imports and no dependencies. The documents and
 * full word-vector lexicon are embedded as data.
 */
export function compileQuestionAnswererCode(
  input: CompileQuestionAnswererInput,
): CompiledQuestionAnswerer {
  const runtimeSource = input.runtimeSource.trim();
  if (runtimeSource.length === 0) {
    throw new Error("The QA runtime source is empty.");
  }

  const name = input.name.trim() || "Q&A model";
  const answerer = createQuestionAnswerer({
    documents: input.documents,
    suggestions: input.suggestions,
    lexicon: input.lexicon,
  });
  const suggestions = answerer.suggestions;
  const modelInfo = buildQaModelInfo({
    name,
    lexicon: input.lexicon,
    suggestions,
    stats: answerer.stats,
    createdAt: input.createdAt,
    updatedAt: input.updatedAt,
  });

  const uniqueTokens = new Set<string>();
  for (const document of input.documents) {
    for (const question of document.questions) {
      for (const token of contentTokens(question)) {
        uniqueTokens.add(token);
      }
    }
    for (const keyword of document.keywords ?? []) {
      for (const token of contentTokens(keyword)) {
        uniqueTokens.add(token);
      }
    }
  }

  const lines: string[] = [];
  lines.push("// Generated by the Gate Forest QA compiler.");
  lines.push(
    `// Model: ${name} — ${answerer.stats.concepts} concept${
      answerer.stats.concepts === 1 ? "" : "s"
    }, ${answerer.stats.variants} question variant${
      answerer.stats.variants === 1 ? "" : "s"
    }.`,
  );
  lines.push(
    `// ${input.lexicon.words.length.toLocaleString()} bundled word vectors (${input.lexicon.bits}-bit). Engine v${QA_ENGINE_VERSION}.`,
  );
  lines.push(
    "// Word vectors are derived from the Word2Bits subset (Apache-2.0).",
  );
  lines.push("//");
  lines.push("// Usage:");
  lines.push('//   import { ask, createAnswerer, DOCUMENTS } from "./qa-model.ts";');
  lines.push(
    '//   ask("How do split effects work?");',
  );
  lines.push(
    '//   const custom = createAnswerer([...DOCUMENTS, { id: "x", questions: ["..."], answer: "..." }]);',
  );
  lines.push("");
  lines.push(runtimeSource);
  lines.push("");
  lines.push("const LEXICON: QaLexicon = {");
  lines.push(`  bits: ${input.lexicon.bits},`);
  lines.push(...emitStringArray("words", input.lexicon.words, 8));
  lines.push(...emitStringArray("vectors", input.lexicon.vectors, 8));
  lines.push("};");
  lines.push("");
  lines.push("export const DOCUMENTS: readonly QaDocument[] = [");
  for (const document of input.documents) {
    lines.push(`  ${safeJson(document)},`);
  }
  lines.push("];");
  lines.push("");
  lines.push("export const SUGGESTIONS: readonly string[] = [");
  for (const suggestion of suggestions) {
    lines.push(`  ${safeJson(suggestion)},`);
  }
  lines.push("];");
  lines.push("");
  lines.push("const defaultAnswerer = createQuestionAnswerer({");
  lines.push("  documents: DOCUMENTS,");
  lines.push("  suggestions: SUGGESTIONS,");
  lines.push("  lexicon: LEXICON,");
  lines.push("});");
  lines.push("");
  lines.push("export const STATS: QaStats = defaultAnswerer.stats;");
  lines.push(
    "export const QUESTIONS: readonly string[] = defaultAnswerer.questions;",
  );
  lines.push("");
  lines.push(`export const MODEL: QaModelInfo = ${safeJson(modelInfo, 2)};`);
  lines.push("");
  lines.push("export function ask(question: string): QaAnswer | null {");
  lines.push("  return defaultAnswerer.ask(question);");
  lines.push("}");
  lines.push("");
  lines.push("export function createAnswerer(");
  lines.push("  documents: readonly QaDocument[] = DOCUMENTS,");
  lines.push("  suggestions: readonly string[] = SUGGESTIONS,");
  lines.push("): QaAnswerer {");
  lines.push("  return createQuestionAnswerer({");
  lines.push("    documents,");
  lines.push("    suggestions,");
  lines.push("    lexicon: LEXICON,");
  lines.push("  });");
  lines.push("}");
  lines.push("");
  lines.push("export function createAnswererFromModel(");
  lines.push("  model: QaModelFile,");
  lines.push("  options: QaModelLoadOptions = {},");
  lines.push("): QaAnswerer {");
  lines.push(
    "  return createAnswererFromModelWithLexicon(model, LEXICON, options);",
  );
  lines.push("}");
  lines.push("");
  lines.push("export function serializeModel(");
  lines.push("  documents: readonly QaDocument[] = DOCUMENTS,");
  lines.push("  options: {");
  lines.push("    readonly name?: string;");
  lines.push("    readonly suggestions?: readonly string[];");
  lines.push("    readonly createdAt?: string;");
  lines.push("    readonly updatedAt?: string;");
  lines.push("  } = {},");
  lines.push("): QaModelFile {");
  lines.push("  return buildQaModelFile(documents, {");
  lines.push("    name: options.name ?? MODEL.name,");
  lines.push("    lexicon: LEXICON,");
  lines.push("    suggestions: options.suggestions ?? SUGGESTIONS,");
  lines.push("    createdAt: options.createdAt ?? MODEL.createdAt,");
  lines.push("    updatedAt: options.updatedAt,");
  lines.push("  });");
  lines.push("}");
  lines.push("");

  const code = lines.join("\n");

  return {
    code,
    filename: `${slugify(name)}.ts`,
    engineVersion: QA_ENGINE_VERSION,
    conceptCount: answerer.stats.concepts,
    variantCount: answerer.stats.variants,
    questionWordCount: answerer.stats.questionWords,
    uniqueTokenCount: uniqueTokens.size,
    lexiconWordCount: input.lexicon.words.length,
    fingerprint: modelInfo.lexicon.fingerprint,
    lineCount: code.trimEnd().split("\n").length,
    byteLength: new TextEncoder().encode(code).length,
  };
}
